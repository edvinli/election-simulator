@dataclass(frozen=True)
class CaseEvaluationResult:
    """Out-of-sample evaluation result for a single (origin, horizon) forecast case."""

    origin_date: date
    horizon_days: int
    target_date: date
    calendar_block_6m: str
    calendar_block_12m: str
    pool_size: int
    # Arm A: Dynamics v2 (All-history ±)
    es_arm_a_v2: float
    crps_arm_a_v2: float
    # Arm B: Recency Control (Recent-50 ±)
    es_arm_b_recent: float
    crps_arm_b_recent: float
    # Arm C: State-Conditioned Primary (50NN ±)
    es_arm_c_50nn: float
    crps_arm_c_50nn: float
    # Arm D: Directional Test (50NN Raw)
    es_arm_d_raw: float
    crps_arm_d_raw: float
    # Sensitivities: 25NN ± and 100NN ±
    es_arm_c_25nn: float
    crps_arm_c_25nn: float
    es_arm_c_100nn: float
    crps_arm_c_100nn: float
    # Paired Differences (positive means Arm C is better / lower score)
    diff_es_v2_minus_50nn: float
    diff_es_recent_minus_50nn: float
    diff_es_50nn_minus_raw: float
    diff_crps_v2_minus_50nn: float
    diff_crps_recent_minus_50nn: float


def get_calendar_block(d: date, months: int = 6) -> str:
    """Format calendar block string (e.g. 2018-H1 or 2018)."""
    if months == 6:
        half = "H1" if d.month <= 6 else "H2"
        return f"{d.year}-{half}"
    return str(d.year)


def _stable_skewness(values: np.ndarray) -> float:
    """Return the biased Fisher-Pearson skewness without cancellation warnings.

    Some threshold-transition bins contain effectively identical changes.  The
    SciPy implementation quite reasonably warns for those inputs, but a
    diagnostic report should represent that case as zero skew rather than
    emit a misleading precision-loss warning.  The calculation below matches
    ``scipy.stats.skew(..., bias=True)`` for finite, non-degenerate values.
    """
    arr = np.asarray(values, dtype=float)
    if arr.size == 0:
        return np.nan
    mean = float(np.mean(arr))
    centered = arr - mean
    second_moment = float(np.mean(centered * centered))
    scale = max(1.0, float(np.max(np.abs(arr))))
    if second_moment <= (np.finfo(float).eps * scale) ** 2:
        return 0.0
    third_moment = float(np.mean(centered * centered * centered))
    return float(third_moment / (second_moment ** 1.5))


def sample_transitions_to_vote_shares(
    origin_clr: np.ndarray,
    candidate_transitions: Sequence[StateTransition],
    draw_indices: np.ndarray,
    sign_flips: np.ndarray,
    use_sign_symmetry: bool = True,
) -> np.ndarray:
    """Generate M vote-share vectors by applying sampled transitions to origin CLR."""
    m_draws = len(draw_indices)
    k_cand = len(candidate_transitions)
    if k_cand <= 0:
        raise ValueError("candidate_transitions must be non-empty")
    indices = np.asarray(draw_indices, dtype=np.int64)
    if indices.ndim != 1 or len(indices) != m_draws or np.any(indices < 0) or np.any(indices >= k_cand):
        raise ValueError("draw_indices must contain valid candidate-pool indices")

    # Extract transition deltas.  Indices are generated by
    # uniform_indices_from_unit_draws; do not apply modulo here because it
    # would silently hide invalid or biased sampling upstream.
    deltas = np.array([candidate_transitions[int(i)].clr_transition for i in indices], dtype=float)
    if use_sign_symmetry:
        deltas = deltas * sign_flips[:, None]

    # Apply to origin CLR
    simulated_clrs = origin_clr[None, :] + deltas

    # Fast vectorized softmax mapping to vote shares summing to 100.0
    exp_mat = np.exp(simulated_clrs)
    vote_shares_matrix = 100.0 * (exp_mat / np.sum(exp_mat, axis=1, keepdims=True))

    return vote_shares_matrix


def uniform_indices_from_unit_draws(unit_draws: np.ndarray, pool_size: int) -> np.ndarray:
    """Map shared U(0,1) draws to unbiased replacement indices.

    Integer modulo sampling is biased whenever the integer range is not an
    exact multiple of ``pool_size``.  A continuous unit-interval draw avoids
    that issue for every pool size while preserving common random-number
    pairing across arms.
    """
    if pool_size <= 0:
        raise ValueError("pool_size must be positive")
    draws = np.asarray(unit_draws, dtype=float)
    if draws.ndim != 1 or not np.isfinite(draws).all() or np.any(draws < 0.0) or np.any(draws >= 1.0):
        raise ValueError("unit_draws must be finite values in [0, 1)")
    return np.minimum((draws * pool_size).astype(np.int64), pool_size - 1)


def evaluate_single_case(
    origin_state: DailyState,
    target_state: DailyState,
    horizon_days: int,
    candidate_pool: List[StateTransition],
    clr_stds: np.ndarray,
    random_seed: int,
    m_draws: int = EVALUATION_DRAWS_COUNT,
) -> Tuple[CaseEvaluationResult, List[Any]]:
    """Evaluate all 4 comparison arms on a single forecast case using common random numbers."""
    origin_d = origin_state.observation_date
    target_d = target_state.observation_date
    actual_shares = target_state.vote_shares

    # Rank candidate transitions by state distance and recency
    sorted_nn_pairs, sorted_recent, audit_records = rank_candidate_transitions(
        origin_state, candidate_pool, clr_stds
    )
    sorted_nn = [tr for tr, _ in sorted_nn_pairs]

    # Generate common random numbers for exact pairing across arms
    rng = np.random.default_rng(random_seed)
    # Shared continuous uniforms avoid modulo bias for arbitrary pool sizes.
    uniform_draws = rng.random(m_draws)
    sign_flips = rng.choice([-1.0, 1.0], size=m_draws)

    # 1. Arm A: Dynamics v2 (All eligible history, sign symmetric)
    idx_a = uniform_indices_from_unit_draws(uniform_draws, len(candidate_pool))
    shares_a = sample_transitions_to_vote_shares(
        origin_state.clr, candidate_pool, idx_a, sign_flips, use_sign_symmetry=True
    )
    es_a = energy_score(shares_a, actual_shares)
    crps_a = float(np.mean([continuous_crps(shares_a[:, p], actual_shares[p]) for p in range(len(ALL_CATEGORIES_9))]))

    # 2. Arm B: Recency Control (Top 50 most recent, sign symmetric)
    top_50_recent = sorted_recent[:PRIMARY_K_NEIGHBORS]
    idx_b = uniform_indices_from_unit_draws(uniform_draws, len(top_50_recent))
    shares_b = sample_transitions_to_vote_shares(
        origin_state.clr, top_50_recent, idx_b, sign_flips, use_sign_symmetry=True
    )
    es_b = energy_score(shares_b, actual_shares)
    crps_b = float(np.mean([continuous_crps(shares_b[:, p], actual_shares[p]) for p in range(len(ALL_CATEGORIES_9))]))

    # 3. Arm C: State-Conditioned Primary (Top 50 nearest states, sign symmetric)
    top_50_nn = sorted_nn[:PRIMARY_K_NEIGHBORS]
    idx_c = uniform_indices_from_unit_draws(uniform_draws, len(top_50_nn))
    shares_c = sample_transitions_to_vote_shares(
        origin_state.clr, top_50_nn, idx_c, sign_flips, use_sign_symmetry=True
    )
    es_c = energy_score(shares_c, actual_shares)
    crps_c = float(np.mean([continuous_crps(shares_c[:, p], actual_shares[p]) for p in range(len(ALL_CATEGORIES_9))]))

    # 4. Arm D: Directional Test (Top 50 nearest states, raw signed)
    shares_d = sample_transitions_to_vote_shares(
        origin_state.clr, top_50_nn, idx_c, sign_flips, use_sign_symmetry=False
    )
    es_d = energy_score(shares_d, actual_shares)
    crps_d = float(np.mean([continuous_crps(shares_d[:, p], actual_shares[p]) for p in range(len(ALL_CATEGORIES_9))]))

    # Sensitivities: 25NN and 100NN
    top_25_nn = sorted_nn[:25]
    shares_c25 = sample_transitions_to_vote_shares(
        origin_state.clr, top_25_nn, uniform_indices_from_unit_draws(uniform_draws, len(top_25_nn)), sign_flips, use_sign_symmetry=True
    )
    es_c25 = energy_score(shares_c25, actual_shares)
    crps_c25 = float(np.mean([continuous_crps(shares_c25[:, p], actual_shares[p]) for p in range(len(ALL_CATEGORIES_9))]))

    top_100_nn = sorted_nn[: min(len(sorted_nn), 100)]
    shares_c100 = sample_transitions_to_vote_shares(
        origin_state.clr, top_100_nn, uniform_indices_from_unit_draws(uniform_draws, len(top_100_nn)), sign_flips, use_sign_symmetry=True
    )
    es_c100 = energy_score(shares_c100, actual_shares)
    crps_c100 = float(np.mean([continuous_crps(shares_c100[:, p], actual_shares[p]) for p in range(len(ALL_CATEGORIES_9))]))

    res = CaseEvaluationResult(
        origin_date=origin_d,
        horizon_days=horizon_days,
        target_date=target_d,
        calendar_block_6m=get_calendar_block(origin_d, 6),
        calendar_block_12m=get_calendar_block(origin_d, 12),
        pool_size=len(candidate_pool),
        es_arm_a_v2=round(es_a, 5),
        crps_arm_a_v2=round(crps_a, 5),
        es_arm_b_recent=round(es_b, 5),
        crps_arm_b_recent=round(crps_b, 5),
        es_arm_c_50nn=round(es_c, 5),
        crps_arm_c_50nn=round(crps_c, 5),
        es_arm_d_raw=round(es_d, 5),
        crps_arm_d_raw=round(crps_d, 5),
        es_arm_c_25nn=round(es_c25, 5),
        crps_arm_c_25nn=round(crps_c25, 5),
        es_arm_c_100nn=round(es_c100, 5),
        crps_arm_c_100nn=round(crps_c100, 5),
        diff_es_v2_minus_50nn=round(es_a - es_c, 5),
        diff_es_recent_minus_50nn=round(es_b - es_c, 5),
        diff_es_50nn_minus_raw=round(es_c - es_d, 5),
        diff_crps_v2_minus_50nn=round(crps_a - crps_c, 5),
        diff_crps_recent_minus_50nn=round(crps_b - crps_c, 5),
    )
    return res, audit_records


def run_calendar_block_bootstrap(
    eval_df: pd.DataFrame,
    metric_col: str,
    block_col: str = "calendar_block_6m",
    n_replications: int = BOOTSTRAP_REPLICATIONS,
    random_seed: int = BASE_RANDOM_SEED,
) -> Dict[str, Any]:
    """Perform calendar-block bootstrap over contiguous blocks to evaluate paired score differences."""
    unique_blocks = sorted(eval_df[block_col].unique())
    n_blocks = len(unique_blocks)
    block_to_values = {b: eval_df[eval_df[block_col] == b][metric_col].values for b in unique_blocks}

    rng = np.random.default_rng(random_seed)
    boot_means = np.zeros(n_replications)

    for r in range(n_replications):
        sampled_blocks = rng.choice(unique_blocks, size=n_blocks, replace=True)
        sampled_vals = np.concatenate([block_to_values[b] for b in sampled_blocks])
        boot_means[r] = np.mean(sampled_vals)

    return {
        "point_mean": round(float(eval_df[metric_col].mean()), 5),
        "bootstrap_se": round(float(np.std(boot_means)), 5),
        "ci_95": [round(float(np.percentile(boot_means, 2.5)), 5), round(float(np.percentile(boot_means, 97.5)), 5)],
        "prob_positive": round(float(np.mean(boot_means > 0)), 4),
        "n_blocks": n_blocks,
    }


def compute_threshold_starting_state_distributions(
    transitions_by_horizon: Dict[int, List[StateTransition]],
) -> pd.DataFrame:
    """Analyze empirical transition distributions for parties starting in half-open threshold bins."""
    records: List[Dict[str, Any]] = []

    for h, transitions in sorted(transitions_by_horizon.items()):
        for low, high, bin_label in THRESHOLD_STARTING_BINS:
            for p in ["L", "KD", "MP", "C", "V", "SD"]:
                # Filter transitions where party p starts in [low, high)
                matched = [
                    (tr.start_composition[p], tr.end_composition[p], tr.end_composition[p] - tr.start_composition[p])
                    for tr in transitions
                    if low <= tr.start_composition[p] < high
                ]

                if not matched:
                    continue

                starts = np.array([m[0] for m in matched], dtype=float)
                ends = np.array([m[1] for m in matched], dtype=float)
                changes = np.array([m[2] for m in matched], dtype=float)
                n_cases = len(changes)

                # Crossing probabilities
                if high <= 4.0:
                    cross_up_prob = float(np.mean(ends >= 4.0))
                    cross_down_prob = np.nan
                elif low >= 4.0:
                    cross_down_prob = float(np.mean(ends < 4.0))
                    cross_up_prob = np.nan
                else:
                    cross_up_prob = float(np.mean((starts < 4.0) & (ends >= 4.0))) / max(1e-5, np.mean(starts < 4.0)) if np.any(starts < 4.0) else np.nan
                    cross_down_prob = float(np.mean((starts >= 4.0) & (ends < 4.0))) / max(1e-5, np.mean(starts >= 4.0)) if np.any(starts >= 4.0) else np.nan

                records.append({
                    "horizon_days": h,
                    "party": p,
                    "starting_bin": bin_label,
                    "bin_low_pct": low,
                    "bin_high_pct": high,
                    "n_transitions": n_cases,
                    "median_starting_share": round(float(np.median(starts)), 2),
                    "median_signed_change_pp": round(float(np.median(changes)), 3),
                    "mean_absolute_change_pp": round(float(np.mean(np.abs(changes))), 3),
                    "variance_change": round(float(np.var(changes)), 4),
                    "skewness_change": round(_stable_skewness(changes), 3) if n_cases >= 8 else np.nan,
                    "crossing_upward_prob": round(cross_up_prob, 4) if np.isfinite(cross_up_prob) else None,
                    "crossing_downward_prob": round(cross_down_prob, 4) if np.isfinite(cross_down_prob) else None,
                })

    return pd.DataFrame(records)
